// Refresh campus restaurants from the Campus Services Office page (cso.hkust.edu.hk/index.php/locations/restaurants).
// Writes src/product/campus/dining-data.ts; review the diff before committing.
// Usage: node scripts/sync-cso-dining.mjs [saved-page.html]  (pass a curl-saved copy when Node cannot reach the site)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const URL_ = 'https://cso.hkust.edu.hk/index.php/locations/restaurants';
const html = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await fetch(URL_).then(r => { if (!r.ok) throw new Error(`CSO ${r.status}`); return r.text(); });
const text = s => s.replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&#0?39;|&rsquo;/g, "'").replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const field = (block, cls) => { const m = new RegExp(`views-field-${cls}[^"]*"[^>]*>([\\s\\S]*?)</div></div>`).exec(block); return m ? text(m[1]) : ''; };
const outlets = [];
const blocks = html.split(/<li class="map-item-/).slice(1);
for (const raw of blocks) {
  const block = raw.slice(0, raw.indexOf('</li>\n          <li') > 0 ? raw.indexOf('</li>\n          <li') : raw.length);
  const name = (/views-field-title name"><span class="field-content">([^<]+)</.exec(block) ?? [])[1];
  if (!name) continue;
  const hours = [...block.matchAll(/paragraph--type--time[^>]*>([\s\S]*?)<\/div>/g)].map(m => text(m[1])).filter(Boolean);
  const pathAdvisor = (/views-field-field-loc-path-advisor-link[\s\S]*?href="([^"]+)"/.exec(block) ?? [])[1]?.replace(/&amp;/g, '&') ?? null;
  const menu = (/views-field-field-loc-attachments[\s\S]*?href="([^"]+)"/.exec(block) ?? [])[1] ?? null;
  const info = (/loc-tab information">\s*<p>([\s\S]*?)<\/p>/.exec(block) ?? [])[1];
  outlets.push({
    id: text(name).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), name: text(name),
    category: field(block, 'field-loc-category'), phone: field(block, 'field-loc-phone-number') || null, hours,
    path_advisor: pathAdvisor, menu: menu ? new URL(menu, 'https://cso.hkust.edu.hk').toString() : null,
    about: info ? text(info).slice(0, 220) : null,
  });
}
if (outlets.length < 10) throw new Error(`Only ${outlets.length} outlets parsed; page layout may have changed.`);
const data = { source: { url: URL_, special_hours: 'https://cso.hkust.edu.hk/special-opening-hours', retrieved_at: new Date().toISOString(), sha256: createHash('sha256').update(html).digest('hex') }, outlets };
writeFileSync(new URL('../src/product/campus/dining-data.ts', import.meta.url), `// Generated by scripts/sync-cso-dining.mjs from the CSO restaurants page. Do not edit by hand.\nexport const diningData = ${JSON.stringify(data, null, 2)} as const;\n`);
console.log(`${outlets.length} outlets written.`);
