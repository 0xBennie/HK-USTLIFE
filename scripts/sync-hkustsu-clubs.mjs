// Refresh the society directory from the HKUST Students' Union website (hkustsu.hkust.edu.hk/societies).
// Writes src/product/life/clubs-data.ts; review the diff before committing.
// Usage: node scripts/sync-hkustsu-clubs.mjs [saved-page.html]  (pass a curl-saved copy when Node cannot reach the site)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const URL_ = 'https://hkustsu.hkust.edu.hk/societies';
const GROUPS = {
  'Art and Cultural Clubs': ['culture', '文化艺术'],
  'Sports Association and Sports Clubs': ['sport', '运动'],
  'ICA and Independent Clubs': ['interest', '兴趣与信仰'],
  'School Societies': ['school', '学院学生会'],
  'Departmental Societies': ['department', '系会'],
  'House Associations': ['house', '舍堂'],
};
const unescape = s => s.replace(/&#0?39;/g, "'").replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const clean = s => unescape(s).replace(/,?\s*HKUSTSU\.?$/i, '').replace(/^HKUSTSU\s+/i, '').replace(/\s+HKUSTSU$/i, '').trim();

const html = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await fetch(URL_).then(r => { if (!r.ok) throw new Error(`HKUSTSU ${r.status}`); return r.text(); });
const summaries = new Map();
for (const m of html.matchAll(/societies\/about\/(\d+)">[\s\S]*?<div class="description[^"]*">([\s\S]*?)<\/div>/g)) {
  const first = unescape(m[2]).split(/\n/).map(x => x.trim()).find(Boolean) ?? '';
  summaries.set(m[1], first.length > 80 ? `${first.slice(0, 78)}…` : first);
}
const clubs = [];
for (const [, label, body] of html.matchAll(/<optgroup label="([^"]+)"[^>]*>([\s\S]*?)<\/optgroup>/g)) {
  const group = GROUPS[label];
  if (!group) continue; // skips placeholder groups such as "test Society"
  for (const [, id, name] of body.matchAll(/<option value="(\d+)">([^<]+)<\/option>/g)) {
    clubs.push({ id: `su-${id}`, name: clean(name), category: group[0], tags: group[1], url: `${URL_}/about/${id}`, summary: summaries.get(id) ?? '' });
  }
}
if (clubs.length < 40) throw new Error(`Only ${clubs.length} societies parsed; page layout may have changed.`);
const data = { source: { url: URL_, retrieved_at: new Date().toISOString(), sha256: createHash('sha256').update(html).digest('hex') }, clubs };
writeFileSync(new URL('../src/product/life/clubs-data.ts', import.meta.url), `// Generated by scripts/sync-hkustsu-clubs.mjs from the HKUST Students' Union society directory. Do not edit by hand.\nexport const clubsData = ${JSON.stringify(data, null, 2)} as const;\n`);
console.log(`${clubs.length} societies written.`);
